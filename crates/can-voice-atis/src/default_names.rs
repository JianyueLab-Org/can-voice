//! 写进配置文件的几个默认名字。
//!
//! # 是数据，不是界面文字——所以是中文，也不跟着界面语言变（#29）
//!
//! 这几个字一旦存进 `atis_profile.json`，就是那份配置、那份构型的**名字**：界面
//! 按名字选中、改名、删除，[`crate::profile::Station::preset`] 按名字取构型。它们
//! 和用户自己起的"华东""南向"是同一种东西，所以照原样存、照原样显示。
//!
//! 考虑过"存中文、显示时换成当前语言"，没有这么做：构型名在界面上还出现在一个
//! 直接编辑名字的输入框里，那里只能是原文，于是同一个名字会在下拉框里是一种语言、
//! 在输入框里是另一种。英文界面的人看到一个中文名字，改个名就是了。
//!
//! 也不能换成英文或者随语言生成：旧版 can-audio 存的就是这几个字，老形状的文件
//! 读进来时也按 [`DEFAULT_PROFILE_NAME`] 起名——换掉的话，同一个人升级之后会看到
//! 一份"默认"和一份新名字并排。
//!
//! **界面上"加一份构型"起的名字是另一回事**，它跟着此刻的界面语言（"构型 2" /
//! "Preset 2"，见 `apps/atis/src/components/StationEditor.vue`）：那是用户自己点出来、
//! 当场看着、随手就改的名字，和他自己敲一个没有区别；这里的三个是没人在场时由程序
//! 写下的，又要和旧版存下的文件对得上。于是英文界面里会并排出现"默认"和
//! "Preset 2"——两个都是名字，改掉哪个都行。
//!
//! 单独放一个文件，是为了让 `can-voice-i18n` 的字典测试只豁免这几个名字，而不是
//! 整个 `profile.rs` / `vatis.rs`：那两个文件里的报错照样要被扫。

/// 没有名字时的配置名，也是老形状的文件转成的那一份配置的名字。
pub const DEFAULT_PROFILE_NAME: &str = "默认";

/// 没有名字时的构型名。新席位自带的那一份就叫这个。
pub const DEFAULT_PRESET_NAME: &str = "默认";

/// vATIS 里没有名字的预设，导进来叫这个。
pub const UNNAMED_PRESET_NAME: &str = "未命名";
